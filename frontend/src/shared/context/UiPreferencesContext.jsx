const UiPreferencesContext = createContext(null)

function readPreferences() {
  try {
    const saved = JSON.parse(localStorage.getItem(storageKey) || '{}')
    return {
      theme: saved.theme === 'dark' ? 'dark' : 'light',
      locale: saved.locale === 'en' ? 'en' : 'vi',
    }
  } catch {
    return { theme: 'light', locale: 'vi' }
  }
}

export function UiPreferencesProvider({ children }) {
  const [preferences, setPreferences] = useState(readPreferences)

  useEffect(() => {
    document.documentElement.dataset.theme = preferences.theme
    document.documentElement.lang = preferences.locale
    localStorage.setItem(storageKey, JSON.stringify(preferences))
  }, [preferences])

  const value = useMemo(
    () => ({
      ...preferences,
      setTheme: (theme) => setPreferences((current) => ({ ...current, theme })),
      setLocale: (locale) => setPreferences((current) => ({ ...current, locale })),
      toggleTheme: () =>
        setPreferences((current) => ({
          ...current,
          theme: current.theme === 'dark' ? 'light' : 'dark',
        })),
      toggleLocale: () =>
        setPreferences((current) => ({
          ...current,
          locale: current.locale === 'vi' ? 'en' : 'vi',
        })),
      t: (key, values = {}) => {
        const template = messages[preferences.locale][key] ?? messages.en[key] ?? key
        return Object.entries(values).reduce(
          (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
          template
        )
      },
    }),
    [preferences]
  )

  return <UiPreferencesContext.Provider value={value}>{children}</UiPreferencesContext.Provider>
}

export function useUiPreferences() {
  const context = useContext(UiPreferencesContext)
  if (!context) throw new Error('useUiPreferences must be used inside UiPreferencesProvider.')
  return context
}
